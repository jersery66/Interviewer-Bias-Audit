"""
Mismatch Sample Error-Attribution Analysis (PHQ-8)
==================================================
Module 13 of the DAIC-WOZ strict reanalysis.

This module operationalises the "why do models err?" question as a SMALL,
REPRODUCIBLE error-attribution analysis that must contain four ingredients:
  (1) mismatch samples (self-report vs interview-evidence disagreement),
  (2) error DIRECTION (underestimate / overestimate),
  (3) human attribution coding (R1-R6, two independent reviewers),
  (4) necessary controls (consistent high / consistent low groups A & B).

It is explicitly NOT a causal proof. The quantitative parts (four-group
error rates, error directions, association tests) are fully computed here
from frozen inputs. The human-attribution coding (R1-R6) is left as a
BLANK coding sheet for human reviewers — this script does NOT fabricate
attribution codes, and does NOT read or emit raw interview text.

Hard constraints (inherited from the strict reanalysis SPEC):
  - Read ONLY frozen input files (same paths as modules 11 / 12).
  - NEVER use any OOF probability as a feature for a new model.
  - ALL merges on `participant_id`.
  - All models fold-local (10x5 participant-level repeated CV).
  - Do NOT read any superseded 01-06 results.
  - Do NOT output raw interview text; the coding sheet carries only IDs +
    structured indicators, with free-text attribution columns left BLANK
    for human reviewers.

Outputs (8 files, all generated by this script):
  attribution_error_direction_table.csv   # Table 1 (quantitative, computed)
  attribution_direction_stats.csv         # Fisher test (mismatch vs consistent error rate)
  coding_pool_all.csv                     # full mismatch+complex-error pool (all rows)
  coding_sheet_selected.csv              # selected subset for full human coding (<=15/type)
  codebook.md                             # R1-R6 definitions + two-reviewer procedure
  attribution_analysis_summary.md         # narrative + Table 1 numbers
  run_manifest.json
  output_manifest_sha256.csv

NOTE: `aggregate_coding.py` is a COMPANION script provided in this directory
(runtime-independent of this generator). It is NOT an output of this script.
Run it AFTER human reviewers fill `coding_sheet_selected.csv` (columns r1_* / r2_*)
to produce Table 2 + Cohen's Kappa.

Author: strict reanalysis (2026-07-09)
"""

