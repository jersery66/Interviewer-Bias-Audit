def build_summary(oof, table_df, stats_df, sel, manifest):
    L = []
    L.append("# 错位样本错误归因分析（定量部分）")
    L.append("")
    L.append(f"> 模块 13 · DAIC-WOZ PHQ-8 · 分析日期 {manifest['created'][:10]}")
    L.append("> 定量部分来自冻结输入与冻结 10×5 参与者级交叉验证，可复现。")
    L.append("> 人工归因（R1–R6）为待完成项，详见 `coding_sheet_selected.csv` 与 `codebook.md`。")
    L.append("")
    L.append("## 1 四组定义与样本量")
    L.append("")
    L.append("- PHQ-8 高 = 总分 ≥ 10；文本证据高 = 覆盖广度 ≥ 5 **或** 证据密度 ≥ 11（并集，操作性定义，非临床诊断）。")
    L.append("- A 一致高（PHQ高+证据高）· B 一致低（PHQ低+证据低）为对照；C 自评高证据低、D 自评低证据高为错位重点组。")
    for g in GROUPS:
        n = int((oof["_group"] == g).sum())
        L.append(f"  - {GROUP_CN[g]}：n = {n}")
    L.append("")
    L.append("## 2 表 1：四组模型错误率与错误方向（定量）")
    L.append("")
    L.append("| 模型 | 分组 | n | 错误数 | 错误率 | 低估数 | 高估数 | 主要错误方向 |")
    L.append("| --- | --- | --: | --: | --: | --: | --: | --- |")
    for _, r in table_df.iterrows():
        L.append(f"| {r['model']} | {r['group_cn']} | {r['n']} | {r['n_error']} | "
                 f"{r['error_rate']} | {r['n_underestimate']} | {r['n_overestimate']} | "
                 f"{r['main_error_direction']} |")
    L.append("")
    L.append("> 注：二分类任务下错误方向由标签决定（PHQ-8 阳性判错=低估，阴性判错=高估），"
             "故 C 组主方向为低估、D 组主方向为高估是输入—标签冲突方向的**直接体现**，"
             "并非独立统计发现；该表用于呈现错位样本错误的集中与方向，而非方向差异检验。")
    L.append("")
    L.append("## 3 错位—错误关联检验（定量）")
    L.append("")
    L.append("| 模型 | Fisher OR(错位vs一致) | Fisher p |")
    L.append("| --- | --: | --: |")
    for _, r in stats_df.iterrows():
        L.append(f"| {r['model']} | {r['fisher_or_mismatch_vs_consistent']} | "
                 f"{r['fisher_p_mismatch_vs_consistent']} |")
    L.append("")
    L.append("## 4 人工归因（待完成）")
    L.append("")
    L.append("- 错位且预测错误的样本池：C 组 %d 例、D 组 %d 例；建议完整编码 %d 例"
             % (int((sel["_group"] == "C_self_high_ev_low").sum()),
                int((sel["_group"] == "D_self_low_ev_high").sum()),
                int((sel["selected_for_coding"] == "是").sum())))
    L.append("- 编码表：完整池 `coding_pool_all.csv`、待编码子集 `coding_sheet_selected.csv`"
             "（均仅含 ID 与结构化指标，含十域 count/pres，归因列留空）。")
    L.append("- 编码手册：`codebook.md`（R1–R6 + 两轮双复核流程）。")
    L.append("- 填完 `coding_sheet_selected.csv` 后，运行本模块提供的 `aggregate_coding.py` "
             "生成表 2（错位类型 × 主要归因）并计算 Cohen's Kappa。")
    L.append("- 本分析为机制性描述，**不作强因果推断**，不对个体作诊断性判断。")
    L.append("")
    return "\n".join(L)


